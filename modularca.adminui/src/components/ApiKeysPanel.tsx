import React, { useCallback, useEffect, useState } from 'react';
import type { NoticeInput } from '@shared/notifications/notice';
import { errorNotice } from '@shared-auth/api/notices';
import { apiGet, apiDeleteWithMfa, apiPostWithMfa } from '../api/client';
import { useStepUp } from './StepUpMfaContext';
import ConfirmModal from './ConfirmModal';
import { StatusBadge } from '@shared/components/cards/StatusBadge';
import { DetailField } from '@shared/components/cards/DetailField';
import { DataTable, type DataTableBulkAction, type DataTableColumn } from '@shared/components/DataTable';
import { NewButton } from '@shared/components/NewButton';
import { actionButton, actionButtonPrimary } from '@shared/components/actionButtons';
import { StepUpOps } from '@shared/generated';
import {
    type ApiKeyRow, type SpaceOption, INSTANCE_SCOPE, INTEGRATION_SCOPE,
    apiKeyBadge, apiKeyHint, apiKeyRequest, apiKeyScopeLabel,
} from './apiKeys';

function formatDate(d: string | null) {
    if (!d) return '-';
    return new Date(d).toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' });
}

interface ApiKeysPanelProps {
    /** `integration` for the infrastructure API, `cert-manager` for the cert-manager issuer. */
    integration: 'integration' | 'cert-manager';
}

interface CreatedKey {
    key: string;
    apiKey: ApiKeyRow;
}

/// The named API keys of one integration: each client holds its own, so one can be replaced or
/// revoked without the others. A key is generated by the server and shown once, here, when it is
/// created; afterwards only its name and last four characters are known.
export const ApiKeysPanel: React.FC<ApiKeysPanelProps> = ({ integration }) => {
    const { requireStepUp } = useStepUp();
    const [keys, setKeys] = useState<ApiKeyRow[]>([]);
    const [spaces, setSpaces] = useState<SpaceOption[]>([]);
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState<NoticeInput | null>(null);
    const [actionError, setActionError] = useState<string | null>(null);
    const [showCreate, setShowCreate] = useState(false);
    const [name, setName] = useState('');
    const [scope, setScope] = useState(INTEGRATION_SCOPE);
    const [expiresInDays, setExpiresInDays] = useState('');
    const [creating, setCreating] = useState(false);
    const [created, setCreated] = useState<CreatedKey | null>(null);
    const [copied, setCopied] = useState(false);
    const [confirmRevoke, setConfirmRevoke] = useState<ApiKeyRow | null>(null);
    const [revoking, setRevoking] = useState(false);

    const load = useCallback(() => {
        setLoading(true);
        apiGet<ApiKeyRow[]>(`/api/v1/admin/api-keys?integration=${encodeURIComponent(integration)}`)
            .then((rows) => { setKeys(Array.isArray(rows) ? rows : []); setError(null); })
            .catch((err) => setError(errorNotice(err, 'The API keys could not be loaded.')))
            .finally(() => setLoading(false));
    }, [integration]);

    useEffect(() => { load(); }, [load]);

    useEffect(() => {
        // The scope list is a convenience: without it a key can still be made for the integration's own scope.
        apiGet<any>('/api/v1/admin/spaces')
            .then((d) => {
                const items = Array.isArray(d) ? d : (d?.items || []);
                setSpaces(items.map((s: any) => ({ id: String(s.id), name: s.name || String(s.id) })));
            })
            .catch(() => setSpaces([]));
    }, []);

    const handleCreate = async () => {
        const request = apiKeyRequest(integration, name, scope, expiresInDays);
        if ('problem' in request) { setActionError(request.problem); return; }
        setCreating(true);
        setActionError(null);
        try {
            const result = await apiPostWithMfa<CreatedKey>('/api/v1/admin/api-keys', request.body, requireStepUp, StepUpOps.CreateApiKey);
            setCreated(result);
            setCopied(false);
            setName('');
            setScope(INTEGRATION_SCOPE);
            setExpiresInDays('');
            setShowCreate(false);
            load();
        } catch (err: any) {
            if (err.message !== 'Step-up MFA cancelled') setActionError(err.message);
        } finally {
            setCreating(false);
        }
    };

    const handleRevoke = async (key: ApiKeyRow) => {
        setActionError(null);
        setRevoking(true);
        try {
            await apiDeleteWithMfa(`/api/v1/admin/api-keys/${key.id}`, requireStepUp, StepUpOps.RevokeApiKey, key.id);
            load();
        } catch (err: any) {
            if (err.message !== 'Step-up MFA cancelled') setActionError(err.message);
        } finally {
            setRevoking(false);
            setConfirmRevoke(null);
        }
    };

    const copyKey = (text: string) => {
        navigator.clipboard.writeText(text).then(() => {
            setCopied(true);
            setTimeout(() => setCopied(false), 2000);
        });
    };

    const columns: DataTableColumn<ApiKeyRow>[] = [
        { key: 'name', header: 'Name', defaultWidth: 200, sortable: true, exportValue: (k) => k.name, render: (k) => <span className="text-ink truncate">{k.name}</span> },
        { key: 'key', header: 'Key', defaultWidth: 110, truncate: false, exportValue: (k) => apiKeyHint(k.hint), render: (k) => <span className="data-mono text-ink-muted">{apiKeyHint(k.hint)}</span> },
        { key: 'status', header: 'Status', defaultWidth: 100, truncate: false, exportValue: (k) => apiKeyBadge(k).label, render: (k) => { const b = apiKeyBadge(k); return <StatusBadge status={b.status} label={b.label} />; } },
        { key: 'scope', header: 'Scope', defaultWidth: 190, exportValue: (k) => apiKeyScopeLabel(k.spaceScope, spaces), render: (k) => <span className="text-xs text-ink truncate">{apiKeyScopeLabel(k.spaceScope, spaces)}</span> },
        { key: 'lastUsed', header: 'Last used', defaultWidth: 160, exportValue: (k) => (k.lastUsedAt ? formatDate(k.lastUsedAt) : 'Never'), render: (k) => <span className="text-xs text-ink-muted">{k.lastUsedAt ? formatDate(k.lastUsedAt) : 'Never'}</span> },
        { key: 'expires', header: 'Expires', defaultWidth: 160, exportValue: (k) => (k.expiresAt ? formatDate(k.expiresAt) : 'Never'), render: (k) => <span className="text-xs text-ink-muted">{k.expiresAt ? formatDate(k.expiresAt) : 'Never'}</span> },
        { key: 'created', header: 'Created', defaultWidth: 160, exportValue: (k) => formatDate(k.createdAt), render: (k) => <span className="text-xs text-ink-muted">{formatDate(k.createdAt)}</span> },
    ];

    // Revoke is step-up gated per key, so it acts on one row at a time.
    const bulkActions: DataTableBulkAction<ApiKeyRow>[] = [
        { label: 'Revoke', single: true, variant: 'danger', enabledFor: (k) => k.status !== 'revoked', onClick: (rows) => setConfirmRevoke(rows[0]) },
    ];

    const drawer = (k: ApiKeyRow) => (
        <div className="text-sm">
            <DetailField label="Name" value={k.name} />
            <DetailField label="Key" value={apiKeyHint(k.hint)} mono />
            <DetailField label="Status" value={apiKeyBadge(k).label} />
            <DetailField label="Scope" value={apiKeyScopeLabel(k.spaceScope, spaces)} />
            <DetailField label="Created" value={`${formatDate(k.createdAt)} by ${k.createdBy}`} />
            <DetailField label="Expires" value={k.expiresAt ? formatDate(k.expiresAt) : 'Never'} />
            <DetailField label="Last used" value={k.lastUsedAt ? formatDate(k.lastUsedAt) : 'Never'} />
            {k.revokedAt && <DetailField label="Revoked" value={`${formatDate(k.revokedAt)} by ${k.revokedBy || 'unknown'}`} />}
            <p className="text-[11px] text-ink-muted pt-3">The key itself was shown once, when it was created. It is not stored and cannot be shown again.</p>
        </div>
    );

    const inputCls = 'w-full px-3 py-1.5 bg-raised border border-line-strong rounded text-sm text-ink placeholder-ink-faint focus:outline-none focus:border-accent';

    return (
        <div className="space-y-3">
            {showCreate && (
                <div className="bg-raised border border-line rounded-lg px-4 py-3 space-y-3">
                    <div className="grid grid-cols-1 md:grid-cols-3 gap-3">
                        <div>
                            <label htmlFor={`api-key-name-${integration}`} className="block text-xs text-ink-muted mb-1">Name</label>
                            <input id={`api-key-name-${integration}`} type="text" value={name} onChange={(e) => setName(e.target.value)}
                                placeholder="e.g. terraform-prod" maxLength={100} className={inputCls} />
                        </div>
                        <div>
                            <label htmlFor={`api-key-scope-${integration}`} className="block text-xs text-ink-muted mb-1">Scope</label>
                            <select id={`api-key-scope-${integration}`} value={scope} onChange={(e) => setScope(e.target.value)} className={inputCls}>
                                <option value={INTEGRATION_SCOPE}>The integration's scope</option>
                                <option value={INSTANCE_SCOPE}>Instance CAs only</option>
                                {spaces.map((s) => <option key={s.id} value={s.id}>Space: {s.name}</option>)}
                            </select>
                        </div>
                        <div>
                            <label htmlFor={`api-key-expiry-${integration}`} className="block text-xs text-ink-muted mb-1">Expires in days (optional)</label>
                            <input id={`api-key-expiry-${integration}`} type="text" inputMode="numeric" value={expiresInDays}
                                onChange={(e) => setExpiresInDays(e.target.value)} placeholder="Never" className={inputCls} />
                        </div>
                    </div>
                    <p className="text-xs text-ink-muted max-w-3xl">
                        The key is generated here and shown once. A key limited to a space or to the instance reaches only those CAs.
                    </p>
                    <div className="flex items-center gap-2">
                        <button type="button" onClick={handleCreate} disabled={creating} className={actionButtonPrimary}>
                            {creating ? 'Generating...' : 'Generate key'}
                        </button>
                        <button type="button" onClick={() => { setShowCreate(false); setActionError(null); }} className={actionButton}>Cancel</button>
                    </div>
                </div>
            )}

            {created && (
                <div className="bg-ok-soft border border-line border-l-4 border-l-ok rounded-lg px-4 py-3">
                    <div className="flex items-center gap-2 mb-2 flex-wrap">
                        <span className="text-ok text-sm font-semibold">Key "{created.apiKey.name}" generated</span>
                        <span className="text-xs text-warn">Copy it now. It is not stored and cannot be shown again.</span>
                    </div>
                    <div className="flex items-center gap-2">
                        <code className="text-ink data-mono bg-sunken px-2 py-0.5 rounded flex-1 break-all">{created.key}</code>
                        <button type="button" onClick={() => copyKey(created.key)} className={actionButton}>{copied ? 'Copied' : 'Copy'}</button>
                    </div>
                    <button type="button" onClick={() => setCreated(null)} className="mt-2 text-xs text-ink-muted hover:text-ink transition-colors">Dismiss</button>
                </div>
            )}

            {actionError && (
                <div className="px-4 py-2 bg-crit-soft border border-crit/40 rounded text-crit text-sm">{actionError}</div>
            )}

            <DataTable<ApiKeyRow>
                tableId={`api-keys-${integration}`}
                title="API keys"
                toolbarAction={<NewButton what="API key" open={showCreate} onClick={() => { setShowCreate(!showCreate); setCreated(null); setActionError(null); }} />}
                rows={keys}
                rowKey={(k) => k.id}
                loading={loading}
                error={error}
                empty="No named keys. Generate one for each client, so one can be revoked without the others."
                columns={columns}
                selectable
                bulkActions={bulkActions}
                exportFileName={`api-keys-${integration}`}
                renderDrawer={drawer}
                drawerTitle={(k) => k.name}
            />

            <ConfirmModal
                isOpen={!!confirmRevoke}
                title="Revoke API key"
                message={confirmRevoke ? `Revoke "${confirmRevoke.name}"? The client holding it is refused from now on. This cannot be undone; generate a new key to replace it.` : ''}
                confirmLabel="Revoke"
                loading={revoking}
                onConfirm={() => confirmRevoke && handleRevoke(confirmRevoke)}
                onCancel={() => setConfirmRevoke(null)}
            />
        </div>
    );
};
