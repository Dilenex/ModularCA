using Microsoft.Extensions.Logging;
using ModularCA.Core.Services;
using ModularCA.Shared.Models.Config;
using ModularCA.Tests.Auth;
using Xunit;

namespace ModularCA.Tests.Core.Services;

/// <summary>
/// RenameTenantToSpace renames each space's <c>org-&lt;slug&gt;-*</c> groups to
/// <c>space-&lt;slug&gt;-*</c>, but cannot edit <c>LdapAuth.GroupToRoleMappings</c> in
/// config.yaml. A mapping that still names the old group resolves to the renamed one, with a
/// warning, at sync and in validation; no other name is resolved.
/// </summary>
public class LdapSpaceGroupRenameTests
{
    public LdapSpaceGroupRenameTests() => LdapGroupSyncService.WarnedRenamedGroups.Clear();

    private static (LdapGroupSyncService Sync, CapturingLogger Log) Sync(ControlledUserWorld w, string? mappings = null)
    {
        var config = new SystemConfig();
        config.LdapAuth.GroupToRoleMappings = mappings;
        var log = new CapturingLogger();
        return (new LdapGroupSyncService(w.Db, config, null!, log), log);
    }

    [Fact]
    public async Task A_mapping_to_a_renamed_org_group_still_grants_the_space_group_and_warns()
    {
        var w = new ControlledUserWorld();
        var users = w.Group("space-a-user", w.SpaceA, null, "Requester", autoGenerated: true);
        w.Db.SaveChanges();
        var (sync, log) = Sync(w, """{"CN=PKI Users,DC=acme":"org-a-user"}""");

        await sync.SyncUserGroupsAsync(w.Plain, ["CN=PKI Users,DC=acme"]);

        Assert.Contains(w.Db.CaGroupMembers, m => m.UserId == w.Plain && m.GroupId == users.Id);
        var warning = Assert.Single(log.Warnings, m => m.Contains("org-a-user"));
        Assert.Contains("space-a-user", warning);
        Assert.Contains("config.yaml", warning);
    }

    [Fact]
    public async Task The_warning_is_logged_once_per_process_not_once_per_scoped_instance()
    {
        var w = new ControlledUserWorld();
        var users = w.Group("space-a-user", w.SpaceA, null, "Requester", autoGenerated: true);
        w.Db.SaveChanges();
        const string mappings = """{"CN=PKI Users,DC=acme":"org-a-user"}""";
        var (first, firstLog) = Sync(w, mappings);
        var (second, secondLog) = Sync(w, mappings);

        await first.SyncUserGroupsAsync(w.Plain, ["CN=PKI Users,DC=acme"]);
        await second.SyncUserGroupsAsync(w.Plain, ["CN=PKI Users,DC=acme"]);
        Assert.Equal("space-a-user", (await second.ResolveRenamedSpaceGroupsAsync(["org-a-user"]))["org-a-user"]);

        Assert.Single(firstLog.Warnings, m => m.Contains("org-a-user"));
        Assert.Empty(secondLog.Warnings);
        Assert.Contains(w.Db.CaGroupMembers, m => m.UserId == w.Plain && m.GroupId == users.Id);
    }

    [Fact]
    public async Task Validation_judges_the_renamed_group_so_a_controlled_one_is_still_refused()
    {
        var w = new ControlledUserWorld();
        w.Group("space-a-admin", w.SpaceA, null, "Administrator", autoGenerated: true);
        w.Group("space-a-user", w.SpaceA, null, "Requester", autoGenerated: true);
        w.Db.SaveChanges();
        var (sync, log) = Sync(w);

        Assert.Null(await sync.ValidateMappingsAsync("""{"CN=x":"org-a-user"}"""));
        var refused = await sync.ValidateMappingsAsync("""{"CN=x":"org-a-admin"}""");
        Assert.NotNull(refused);
        Assert.Contains("space-a-admin", refused);
        Assert.Contains(log.Warnings, m => m.Contains("org-a-admin") && m.Contains("space-a-admin"));
    }

    [Theory]
    [InlineData("org-a-user", "org-a-user")]
    [InlineData("tenant-a-user", null)]
    [InlineData("org-a-owner", null)]
    [InlineData("org-missing-user", null)]
    public async Task Only_an_absent_org_name_whose_space_name_exists_resolves(string mapped, string? existingOldName)
    {
        var w = new ControlledUserWorld();
        w.Group("space-a-user", w.SpaceA, null, "Requester");
        w.Group("space-a-owner", w.SpaceA, null, "Requester");
        w.Group("space-a-user-x", w.SpaceA, null, "Requester");
        if (existingOldName != null)
            w.Group(existingOldName, w.SpaceA, null, "Requester");
        w.Db.SaveChanges();
        var (sync, log) = Sync(w);

        Assert.Empty(await sync.ResolveRenamedSpaceGroupsAsync([mapped]));
        Assert.Empty(log.Warnings);
    }

    [Fact]
    public async Task Direct_group_names_without_mappings_are_not_resolved()
    {
        var w = new ControlledUserWorld();
        var users = w.Group("space-a-user", w.SpaceA, null, "Requester", autoGenerated: true);
        w.Db.SaveChanges();
        var (sync, _) = Sync(w);

        await sync.SyncUserGroupsAsync(w.Plain, ["org-a-user"]);

        Assert.DoesNotContain(w.Db.CaGroupMembers, m => m.UserId == w.Plain && m.GroupId == users.Id);
    }

    [Fact]
    public async Task A_save_rewrites_renamed_org_targets_and_leaves_the_rest()
    {
        var w = new ControlledUserWorld();
        w.Group("space-a-user", w.SpaceA, null, "Requester", autoGenerated: true);
        w.Group("org-b-user", w.SpaceB, null, "Requester");
        w.Group("space-b-user", w.SpaceB, null, "Requester");
        w.Db.SaveChanges();
        var (sync, _) = Sync(w);

        var rewritten = await sync.RewriteRenamedSpaceGroupsAsync(
            """{"CN=A":"org-a-user","CN=B":"org-b-user","CN=C":"org-missing-user","CN=D":"custom"}""");

        var map = System.Text.Json.JsonSerializer.Deserialize<Dictionary<string, string>>(rewritten!)!;
        Assert.Equal("space-a-user", map["CN=A"]);
        Assert.Equal("org-b-user", map["CN=B"]);
        Assert.Equal("org-missing-user", map["CN=C"]);
        Assert.Equal("custom", map["CN=D"]);
    }

    [Fact]
    public async Task Mappings_with_nothing_to_rewrite_are_returned_unchanged()
    {
        var w = new ControlledUserWorld();
        w.Group("space-a-user", w.SpaceA, null, "Requester");
        w.Db.SaveChanges();
        var (sync, _) = Sync(w);
        const string mappings = """{"CN=A": "space-a-user"}""";

        Assert.Same(mappings, await sync.RewriteRenamedSpaceGroupsAsync(mappings));
        Assert.Null(await sync.RewriteRenamedSpaceGroupsAsync(null));
    }

    [Fact]
    public async Task Startup_lists_the_renamed_targets_once_and_sync_does_not_repeat_them()
    {
        var w = new ControlledUserWorld();
        var users = w.Group("space-a-user", w.SpaceA, null, "Requester", autoGenerated: true);
        w.Db.SaveChanges();
        var (sync, log) = Sync(w, """{"CN=PKI Users,DC=acme":"org-a-user"}""");

        var warning = await sync.RenamedMappingTargetsWarningAsync();
        await sync.SyncUserGroupsAsync(w.Plain, ["CN=PKI Users,DC=acme"]);

        Assert.NotNull(warning);
        Assert.Contains("'org-a-user' is now 'space-a-user'", warning);
        Assert.Empty(log.Warnings);
        Assert.Contains(w.Db.CaGroupMembers, m => m.UserId == w.Plain && m.GroupId == users.Id);
        Assert.Null(await Sync(w, """{"CN=x":"space-a-user"}""").Sync.RenamedMappingTargetsWarningAsync());
    }

    internal sealed class CapturingLogger : ILogger<LdapGroupSyncService>
    {
        public List<string> Warnings { get; } = [];

        public IDisposable? BeginScope<TState>(TState state) where TState : notnull => null;

        public bool IsEnabled(LogLevel logLevel) => true;

        public void Log<TState>(LogLevel logLevel, EventId eventId, TState state, Exception? exception, Func<TState, Exception?, string> formatter)
        {
            if (logLevel >= LogLevel.Warning)
                Warnings.Add(formatter(state, exception));
        }
    }
}
