using System.Text.Json;
using ModularCA.Core.Services;
using ModularCA.Shared.Authorization;
using ModularCA.Shared.Entities;
using ModularCA.Tests.TestUtils;
using Xunit;

namespace ModularCA.Tests.Core.Services;

/// <summary>
/// A key ceremony on an existing CA whose scope has no policy takes its quorum from the CA's
/// Administrator group. The CA's Operator group also holds <c>ca.manage</c> and must never be
/// picked, whatever order the rows come back in.
/// </summary>
public class CaAdminGroupQuorumTests
{
    [Fact]
    public async Task A_ca_ceremony_takes_the_quorum_of_the_cas_auto_generated_administrator_group()
    {
        using var db = InMemoryDbContextFactory.Create();
        var gone = new SpaceEntity { Name = "Gone", Slug = "gone", IsDeleted = true };
        var ca = new CertificateAuthorityEntity { Id = Guid.NewGuid(), Name = "x", Label = "x", SpaceId = gone.Id };
        db.Spaces.Add(gone);
        db.CertificateAuthorities.Add(ca);
        void Group(string template, int quorum, bool auto, string[] caps)
        {
            var g = new CaGroupEntity
            {
                Name = $"{template}-{Guid.NewGuid():N}", DisplayName = template, CertificateAuthorityId = ca.Id, SpaceId = gone.Id,
                TemplateName = template, IsAutoGenerated = auto, RequiredQuorum = quorum,
            };
            db.CaGroups.Add(g);
            foreach (var c in caps)
                db.CapabilityGrants.Add(new CapabilityGrantEntity { GroupId = g.Id, Capability = c });
        }
        // Inserted first, so an unordered pick finds them first.
        Group("Operator", 1, auto: true, Capabilities.OperatorTemplate);
        Group("Administrator", 5, auto: false, Capabilities.AdministratorTemplate);
        Group("Administrator", 3, auto: true, Capabilities.AdministratorTemplate);
        await db.SaveChangesAsync();

        var ceremony = await new KeyCeremonyService(db, new RecordingAuditService(), quorumGuard: new OpenQuorumGuard())
            .InitiateAsync("RevokeCa", "x", ca.Id.ToString(), Guid.NewGuid(), "op", JsonSerializer.Serialize(new { SpaceId = gone.Id }));

        Assert.Equal(3, ceremony.RequiredApprovals);
    }
}
