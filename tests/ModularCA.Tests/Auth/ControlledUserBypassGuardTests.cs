        var bUser = w.User("buser", w.B1Requester);

        await Sync(w.Db).SyncUserGroupsAsync(bUser, new List<string> { b1Other.Name, w.A1Requester.Name });

        var groups = w.Db.CaGroupMembers.Where(m => m.UserId == bUser).Select(m => m.GroupId).ToHashSet();
        Assert.DoesNotContain(b1Other.Id, groups);
        Assert.DoesNotContain(w.A1Requester.Id, groups);
    }

    // ---- service identities ------------------------------------------------------------------

    private static ServiceIdentityService Identities(ControlledUserWorld w)
        => new(w.Db, new CaGroupAuthorizationService(w.Db, NullLogger<CaGroupAuthorizationService>.Instance));

    private static void GrantSystemManage(ControlledUserWorld w, CaGroupEntity group)
    {
        w.Db.CapabilityGrants.Add(new CapabilityGrantEntity { GroupId = group.Id, Capability = Capabilities.SystemManage });
        w.Db.SaveChanges();
    }

    [Fact]
    public async Task A_non_super_cannot_put_a_service_identity_into_a_controlled_group()
    {
        var w = new ControlledUserWorld();
        GrantSystemManage(w, w.SystemAdminGroup);
        GrantSystemManage(w, w.SuperGroup);
        var svc = Identities(w);
        var spec = new ServiceIdentitySpec("svc-a1", null, null, new ServiceIdentityScope(null, w.CaA1), new[] { w.A1Admin.Id });

        await Assert.ThrowsAsync<UnauthorizedAccessException>(() => svc.CreateAsync(w.SystemAdmin, spec));
        Assert.False(w.Db.Users.Any(u => u.Username == "svc-a1"));

        var plainIdentity = await svc.CreateAsync(w.SystemAdmin, spec with { Username = "svc-plain", GroupIds = new[] { w.A1Requester.Id } });
        await Assert.ThrowsAsync<UnauthorizedAccessException>(() => svc.SetGroupsAsync(w.SystemAdmin, plainIdentity.Id, new[] { w.A1Requester.Id, w.A1Admin.Id }));

        var created = await svc.CreateAsync(w.Super, spec);
        Assert.True(w.Db.CaGroupMembers.Any(m => m.UserId == created.Id && m.GroupId == w.A1Admin.Id));
    }

    [Fact]
    public async Task A_non_super_cannot_remove_or_delete_a_service_identity_holding_a_controlled_group()
    {
        var w = new ControlledUserWorld();
        GrantSystemManage(w, w.SystemAdminGroup);
        GrantSystemManage(w, w.SuperGroup);
        var svc = Identities(w);
        var created = await svc.CreateAsync(w.Super,
            new ServiceIdentitySpec("svc-a1", null, null, new ServiceIdentityScope(null, w.CaA1), new[] { w.A1Admin.Id }));

        await Assert.ThrowsAsync<UnauthorizedAccessException>(() => svc.SetGroupsAsync(w.SystemAdmin, created.Id, Array.Empty<Guid>()));
        await Assert.ThrowsAsync<UnauthorizedAccessException>(() => svc.DeleteAsync(w.SystemAdmin, created.Id));
        Assert.True(w.Db.Users.Any(u => u.Id == created.Id));

        await svc.DeleteAsync(w.Super, created.Id);
        Assert.False(w.Db.Users.Any(u => u.Id == created.Id));
    }
