        var role = w.Role(Capabilities.SystemManage);
        w.Db.RoleAssignments.Add(new RoleAssignmentEntity { RoleId = role.Id, GroupId = custom.Id });
        w.Db.RoleAssignments.Add(new RoleAssignmentEntity { RoleId = w.Role(Capabilities.CaManage).Id, GroupId = tenantWide.Id });
        w.Db.SaveChanges();

        Assert.Equal(new ControlledTier(ControlledTierLevel.CaAdmin, w.CaA1) { TenantId = w.TenantA }, await w.Controlled.ClassifyGroupAsync(custom));
