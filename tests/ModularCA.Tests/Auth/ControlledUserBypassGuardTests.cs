    [Fact]
    public async Task A_non_super_may_not_leave_the_scope_with_only_themselves()
    {
        var w = new ControlledUserWorld();
        Deactivate(w, w.Super);
        Deactivate(w, w.SystemAdmin);
        var actor = w.User("tenant-admin-1", w.OrgAdminA);
        var target = w.User("tenant-admin-2", w.OrgAdminA);
        var tier = new ControlledTier(ControlledTierLevel.OrgAdmin, null) { TenantId = w.TenantA };

        Assert.Equal(0, await w.Controlled.CountDominatingControlledUsersAsync(tier, target, actorUserId: actor));

        // Accounts that cannot act do not count: locked, service identity, or holding the tier
        // only through a soft-deleted tenant.
        var locked = w.User("locked-admin", w.OrgAdminA);
        w.Db.Users.Single(u => u.Id == locked).IsLocked = true;
        var service = w.User("svc-admin", w.OrgAdminA);
        w.Db.Users.Single(u => u.Id == service).IsServiceIdentity = true;
        w.Db.SaveChanges();
        Assert.Equal(0, await w.Controlled.CountDominatingControlledUsersAsync(tier, target, actorUserId: actor));

        var third = w.User("tenant-admin-3", w.OrgAdminA);
        Assert.Equal(1, await w.Controlled.CountDominatingControlledUsersAsync(tier, target, actorUserId: actor));
        w.Db.Tenants.IgnoreQueryFilters().Single(t => t.Id == w.TenantA).IsDeleted = true;
        w.Db.SaveChanges();
        Assert.Equal(0, await w.Controlled.CountDominatingControlledUsersAsync(tier, target, actorUserId: actor));
    }

    private static void Deactivate(ControlledUserWorld w, Guid userId)
    {
        w.Db.Users.Single(u => u.Id == userId).IsActive = false;
        w.Db.SaveChanges();
    }

    [Fact]
    public async Task Deleting_a_user_whose_tiers_span_scopes_needs_a_system_admin()
    {
        var w = new ControlledUserWorld();
        var svc = w.Controlled;
        var systemAdmin = new ControlledTier(ControlledTierLevel.SystemAdmin, null);

        // An org admin of A who also administers CA A1 is covered by org-admin(A).
        var orgAndCa = w.User("org-and-ca", w.OrgAdminA, w.A1Admin);
        Assert.Equal(new ControlledTier(ControlledTierLevel.OrgAdmin, null) { TenantId = w.TenantA }, await svc.GetDeletionTierAsync(orgAndCa));

