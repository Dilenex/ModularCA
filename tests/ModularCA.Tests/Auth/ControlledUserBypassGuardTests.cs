        w.Db.SaveChanges();
        await Assert.ThrowsAsync<ControlledUserChangeRefusedException>(() => w.Controlled.ApplyApprovedAsync(second.Id));
        Assert.False(w.Db.UserCapabilityGrants.Any(g => g.UserId == w.Plain));
    }

