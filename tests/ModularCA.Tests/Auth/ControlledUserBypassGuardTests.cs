/// <summary>
/// A small tenancy with every tier the controlled-user ceremony reasons about: system-super,
/// system-admin, a CA administrator, an org administrator and uncontrolled requester groups in
/// two tenants. Shared by the service-level and endpoint-level bypass tests.
/// </summary>
internal sealed class ControlledUserWorld
{
    public ModularCADbContext Db { get; }
    public Guid TenantA { get; } = Guid.NewGuid();
    public Guid TenantB { get; } = Guid.NewGuid();
    public Guid CaA1 { get; } = Guid.NewGuid();
    public Guid CaA2 { get; } = Guid.NewGuid();
    public Guid CaB1 { get; } = Guid.NewGuid();

    public CaGroupEntity SuperGroup { get; }
    public CaGroupEntity SystemAdminGroup { get; }
    public CaGroupEntity A1Admin { get; }
    public CaGroupEntity A2Admin { get; }
    public CaGroupEntity OrgAdminA { get; }
    public CaGroupEntity A1Requester { get; }
    public CaGroupEntity B1Requester { get; }
    public CaGroupEntity SystemOperatorGroup { get; }
    public CaGroupEntity SystemAuditorGroup { get; }

    public Guid Super { get; }
    public Guid SystemAdmin { get; }
    public Guid A1AdminUser { get; }
    public Guid Plain { get; }
    public Guid Operator { get; }
    public Guid Auditor { get; }

    public ControlledUserCeremonyService Controlled => new(Db, null!, null!, NullLogger<ControlledUserCeremonyService>.Instance);

    public ControlledUserWorld() : this(InMemoryDbContextFactory.Create()) { }

    /// <summary>Builds the world in <paramref name="db"/>, e.g. a named store a second context can open.</summary>
    public ControlledUserWorld(ModularCADbContext db)
    {
        Db = db;
        Db.Tenants.AddRange(
            new TenantEntity { Id = TenantA, Name = "A", Slug = "a" },
            new TenantEntity { Id = TenantB, Name = "B", Slug = "b" });
        Db.CertificateAuthorities.AddRange(
            new CertificateAuthorityEntity { Id = CaA1, Name = "a1", Label = "a1", TenantId = TenantA },
            new CertificateAuthorityEntity { Id = CaA2, Name = "a2", Label = "a2", TenantId = TenantA },
            new CertificateAuthorityEntity { Id = CaB1, Name = "b1", Label = "b1", TenantId = TenantB });

        SuperGroup = Group("system-super", null, null, "Administrator", system: true, super: true);
        SystemAdminGroup = Group("system-admin", null, null, "Administrator", system: true);
        SystemOperatorGroup = Group("system-operator", null, null, "Operator", system: true);
        SystemAuditorGroup = Group("system-auditor", null, null, "Auditor", system: true);
        A1Admin = Group("org_a1_admin", TenantA, CaA1, "Administrator");
        A2Admin = Group("org_a2_admin", TenantA, CaA2, "Administrator");
        OrgAdminA = Group("tenant-a-admin", TenantA, null, "Administrator");
        A1Requester = Group("org_a1_requester", TenantA, CaA1, "Requester");
        B1Requester = Group("org_b1_requester", TenantB, CaB1, "Requester");

        Super = User("super", SuperGroup);
        SystemAdmin = User("sysadmin", SystemAdminGroup);
        Operator = User("sysoperator", SystemOperatorGroup);
        Auditor = User("sysauditor", SystemAuditorGroup);
        A1AdminUser = User("a1admin", A1Admin);
        Plain = User("plain", A1Requester);
        Db.SaveChanges();
    }

    /// <summary>
    /// Adds a group and, like <c>RoleAssignmentHelper.AssignBuiltInRoleToGroup</c>, seeds the direct
    /// capability grants of its template, so tiers derived from capability match a real deployment.
    /// </summary>
    public CaGroupEntity Group(string name, Guid? tenantId, Guid? caId, string? template, bool system = false, bool super = false, bool autoGenerated = false)
    {
        var g = new CaGroupEntity
        {
            Id = Guid.NewGuid(), Name = name, DisplayName = name, TenantId = tenantId, CertificateAuthorityId = caId,
            TemplateName = template, IsSystemGroup = system, IsSystemTierSuper = super, IsAutoGenerated = autoGenerated,
        };
        Db.CaGroups.Add(g);
        var caps = template switch
        {
            "Administrator" => Capabilities.AdministratorTemplate,
            "Operator" => Capabilities.OperatorTemplate,
            "Auditor" => Capabilities.AuditorTemplate,
            "Requester" => Capabilities.RequesterTemplate,
            _ => Array.Empty<string>(),
        };
        foreach (var c in caps)
            Db.CapabilityGrants.Add(new CapabilityGrantEntity { GroupId = g.Id, Capability = c });
        return g;
    }

    /// <summary>A role carrying <paramref name="caps"/>.</summary>
    public RoleEntity Role(params string[] caps)
    {
        var role = new RoleEntity { Name = $"role-{Guid.NewGuid():N}" };
        Db.Roles.Add(role);
        foreach (var c in caps)
            Db.RoleCapabilities.Add(new RoleCapabilityEntity { RoleId = role.Id, Capability = c });
        Db.SaveChanges();
        return role;
    }

    public Guid User(string username, params CaGroupEntity[] groups)
    {
        var id = Guid.NewGuid();
        Db.Users.Add(new UserEntity { Id = id, Username = username, Email = $"{username}@x" });
        foreach (var g in groups)
            Db.CaGroupMembers.Add(new CaGroupMemberEntity { GroupId = g.Id, UserId = id });
        Db.SaveChanges();
        return id;
    }
}

/// <summary>
/// Service-level guards that close the controlled-user ceremony bypasses: account administration
/// of a privileged user, the last-holder counts behind group and role changes, LDAP group sync, and
/// service-identity membership of controlled groups.
