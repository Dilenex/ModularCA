        }, minted, initiator, w.User("a1-approver-2", w.A1Admin));
        await w.Controlled.ApplyApprovedAsync(second.Id);
        Assert.False(w.Db.CaGroupMembers.Any(m => m.GroupId == w.A1Admin.Id && m.UserId == w.A1AdminUser));
