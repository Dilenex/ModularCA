    private static KeyCeremonyEntity ApprovedCeremony(ControlledUserWorld w, ControlledUserChangeParameters p, ControlledTier minted,
        Guid initiator, params Guid[] approvers)
    {
        p.MintedTierLevel = (int)minted.Level;
        p.MintedTierCaId = minted.CaId;
        p.MintedTierTenantId = minted.TenantId;
        var ceremony = new KeyCeremonyEntity
        {
            OperationType = "ControlledUserChange",
            CeremonyType = ModularCA.Shared.Enums.CeremonyType.ControlledUserChange,
            InitiatedByUserId = initiator,
            RequiredApprovals = Math.Max(1, approvers.Length),
            CurrentApprovals = approvers.Length,
            Status = "Approved",
            ExpiresAt = DateTime.UtcNow.AddHours(1),
            ParametersJson = System.Text.Json.JsonSerializer.Serialize(p),
            ApprovalsJson = System.Text.Json.JsonSerializer.Serialize(approvers.Select(a => new ApprovalRecord
            {
                UserId = a, Username = a.ToString(), Timestamp = DateTime.UtcNow, Decision = "Approved",
            }).ToList()),
            TenantId = minted.TenantId,
        };
        w.Db.KeyCeremonies.Add(ceremony);
        w.Db.SaveChanges();
        return ceremony;
    }

    private static Guid OrgOperator(ControlledUserWorld w, string name)
    {
        var id = w.User(name);
        w.Db.UserCapabilityGrants.Add(new UserCapabilityGrantEntity { UserId = id, Capability = Capabilities.CaManage, TenantId = w.TenantA });
        w.Db.SaveChanges();
        return id;
    }

    [Fact]
    public async Task A_role_that_gains_system_manage_while_its_assignment_is_pending_is_refused_at_execute()
    {
        var w = new ControlledUserWorld();
        var initiator = OrgOperator(w, "op-initiator");
        var approver = OrgOperator(w, "op-approver");
        var role = w.Role(Capabilities.CaManage);
        var minted = new ControlledTier(ControlledTierLevel.OrgOperator, null) { TenantId = w.TenantA };
        var p = new ControlledUserChangeParameters { ChangeType = "AssignRole", TargetUserId = w.Plain, RoleId = role.Id, TenantId = w.TenantA };

        // The awaiting assignment counts as an assignment for the role-change guard.
        Assert.Empty(await w.Controlled.TiersConferredByRoleAsync(role.Id, new[] { Capabilities.SystemManage }));
        var ceremony = ApprovedCeremony(w, p, minted, initiator, approver);
        Assert.Contains(new ControlledTier(ControlledTierLevel.OrgAdmin, null) { TenantId = w.TenantA },
            await w.Controlled.TiersConferredByRoleAsync(role.Id, new[] { Capabilities.SystemManage }));

        w.Db.RoleCapabilities.Add(new RoleCapabilityEntity { RoleId = role.Id, Capability = Capabilities.SystemManage });
        w.Db.SaveChanges();

        var ex = await Assert.ThrowsAsync<ControlledUserChangeRefusedException>(() => w.Controlled.ApplyApprovedAsync(ceremony.Id));
        Assert.True(ex.CeremonyExpired);
        Assert.Equal("Expired", w.Db.KeyCeremonies.Single(c => c.Id == ceremony.Id).Status);
        Assert.False(w.Db.RoleAssignments.Any(ra => ra.RoleId == role.Id));
    }

