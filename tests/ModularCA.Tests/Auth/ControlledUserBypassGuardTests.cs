    [Fact]
    public async Task The_last_user_guard_counts_a_super_actor_but_not_a_non_super_one()
    {
        var w = new ControlledUserWorld();
        var svc = w.Controlled;
        var systemAdmin = new ControlledTier(ControlledTierLevel.SystemAdmin, null);

        // A super removing the only system admin still leaves the super, who dominates every scope.
