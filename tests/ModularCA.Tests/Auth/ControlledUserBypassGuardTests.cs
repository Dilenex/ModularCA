    [Fact]
    public async Task Only_a_dominating_actor_may_administer_a_controlled_account()
    {
        var w = new ControlledUserWorld();
        var svc = w.Controlled;

        Assert.False(await svc.CanAdministerAccountAsync(w.SystemAdmin, w.Super));
        Assert.True(await svc.CanAdministerAccountAsync(w.Super, w.SystemAdmin));
        Assert.True(await svc.CanAdministerAccountAsync(w.SystemAdmin, w.A1AdminUser));
        Assert.False(await svc.CanAdministerAccountAsync(w.A1AdminUser, w.SystemAdmin));

        var a1Peer = w.User("a1peer", w.A1Admin);
        Assert.True(await svc.CanAdministerAccountAsync(w.A1AdminUser, a1Peer));

        var a2Admin = w.User("a2admin", w.A2Admin);
        Assert.False(await svc.CanAdministerAccountAsync(w.A1AdminUser, a2Admin));

        var multi = w.User("multi", w.A1Admin, w.A2Admin);
        Assert.False(await svc.CanAdministerAccountAsync(w.A1AdminUser, multi));

        Assert.True(await svc.CanAdministerAccountAsync(w.A1AdminUser, w.Plain));
    }

    [Fact]
    public async Task System_operators_hold_the_system_operator_tier_auditors_none_and_neither_administers_a_privileged_account()
    {
        var w = new ControlledUserWorld();
        var svc = w.Controlled;
        var sysOp = new ControlledTier(ControlledTierLevel.SystemOperator, null);

        Assert.Equal(sysOp, Assert.Single(await svc.GetUserTiersAsync(w.Operator)));
        Assert.Equal(sysOp, await svc.GetDeletionTierAsync(w.Operator));
        Assert.Empty(await svc.GetUserTiersAsync(w.Auditor));
        Assert.Null(await svc.GetDeletionTierAsync(w.Auditor));

        // ca.manage at instance scope from a direct grant or a role on the account is the same tier.
        var viaGrant = w.User("global-ca-manage");
        w.Db.UserCapabilityGrants.Add(new UserCapabilityGrantEntity { UserId = viaGrant, Capability = Capabilities.CaManage });
        var viaRole = w.User("global-ca-manage-role");
        w.Db.RoleAssignments.Add(new RoleAssignmentEntity { RoleId = w.Role(Capabilities.CaManage).Id, UserId = viaRole });
        w.Db.SaveChanges();
        Assert.Equal(sysOp, Assert.Single(await svc.GetUserTiersAsync(viaGrant)));
        Assert.Equal(sysOp, Assert.Single(await svc.GetUserTiersAsync(viaRole)));
        Assert.Equal(sysOp, svc.ClassifyCapabilityGrant(Capabilities.CaManage, null));
        Assert.Null(svc.ClassifyCapabilityGrant(Capabilities.CaManage, w.CaA1));
        Assert.False(await svc.CanAdministerAccountAsync(w.A1AdminUser, viaGrant));
        Assert.True(await svc.CanAdministerAccountAsync(w.SystemAdmin, viaGrant));

        foreach (var actor in new[] { w.Operator, w.Auditor })
        {
            Assert.False(await svc.CanAdministerAccountAsync(actor, w.SystemAdmin));
            Assert.False(await svc.CanAdministerAccountAsync(actor, w.Super));
            Assert.False(await svc.CanAdministerAccountAsync(actor, w.A1AdminUser));
            Assert.True(await svc.CanAdministerAccountAsync(actor, w.Plain));
        }

        // A system-group member is administered only by system-admin or super, not by a CA admin.
        Assert.False(await svc.CanAdministerAccountAsync(w.A1AdminUser, w.Operator));
        Assert.True(await svc.CanAdministerAccountAsync(w.SystemAdmin, w.Operator));
    }

    [Fact]
    public async Task System_manage_from_a_direct_grant_or_a_role_assignment_is_system_admin()
    {
        var w = new ControlledUserWorld();
        var svc = w.Controlled;
        var viaGrant = w.User("via-grant");
        w.Db.UserCapabilityGrants.Add(new UserCapabilityGrantEntity { UserId = viaGrant, Capability = Capabilities.SystemManage });
        var viaRole = w.User("via-role");
        w.Db.RoleAssignments.Add(new RoleAssignmentEntity { RoleId = w.Role(Capabilities.SystemManage).Id, UserId = viaRole });
        var tenantScoped = w.User("tenant-scoped");
        w.Db.UserCapabilityGrants.Add(new UserCapabilityGrantEntity { UserId = tenantScoped, Capability = Capabilities.SystemManage, TenantId = w.TenantA });
        var caScoped = w.User("ca-scoped");
        w.Db.RoleAssignments.Add(new RoleAssignmentEntity { RoleId = w.Role(Capabilities.SystemManage).Id, UserId = caScoped, CertificateAuthorityId = w.CaA1 });
        w.Db.SaveChanges();

        var systemAdmin = new ControlledTier(ControlledTierLevel.SystemAdmin, null);
        Assert.Contains(systemAdmin, await svc.GetUserTiersAsync(viaGrant));
        Assert.Contains(systemAdmin, await svc.GetUserTiersAsync(viaRole));
        Assert.Equal(systemAdmin, await svc.GetDeletionTierAsync(viaRole));
        Assert.Equal(new ControlledTier(ControlledTierLevel.OrgAdmin, null) { TenantId = w.TenantA }, Assert.Single(await svc.GetUserTiersAsync(tenantScoped)));
        Assert.Equal(new ControlledTier(ControlledTierLevel.CaAdmin, w.CaA1) { TenantId = w.TenantA }, Assert.Single(await svc.GetUserTiersAsync(caScoped)));

        // A CA admin may no longer reset these accounts; a system admin may.
        Assert.False(await svc.CanAdministerAccountAsync(w.A1AdminUser, viaGrant));
        Assert.False(await svc.CanAdministerAccountAsync(w.A1AdminUser, viaRole));
        Assert.True(await svc.CanAdministerAccountAsync(w.A1AdminUser, caScoped));
        Assert.True(await svc.CanAdministerAccountAsync(w.SystemAdmin, viaRole));
    }

    [Fact]
    public async Task A_group_given_a_system_manage_role_classifies_by_capability()
    {
        var w = new ControlledUserWorld();
        var custom = w.Group("custom-a1", w.TenantA, w.CaA1, "Requester");
        var tenantWide = w.Group("custom-tenant-a", w.TenantA, null, null);
        w.Db.SaveChanges();
