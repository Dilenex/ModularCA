using System.Security.Cryptography;
using System.Text;
using ModularCA.Migrate;
using Xunit;

namespace ModularCA.Tests.Migrate;

/// <summary>
/// The parts of the migration helper that can be exercised without two database servers.
/// <para>
/// The copy itself needs a MariaDB and a PostgreSQL and belongs to a rehearsal, not a unit suite.
/// What is pinned here is everything that decides <em>what</em> gets copied and what it is turned
/// into on the way — the column selection, the type conversions, and the one table that does not
/// copy across as it stands. Those are the parts that would be wrong silently.
/// </para>
/// </summary>
public class MigrationHelperTests
{
    // ── The shape of the copy ─────────────────────────────────────────────────

    [Fact]
    public void The_concurrency_token_is_never_written()
    {
        // xmin is a PostgreSQL system column the server maintains. Including it in an INSERT is
        // an error, not a preference, and it is a shadow property so nothing in the entity types
        // makes it visible — exactly the kind of column a hand-written list would carry by
        // accident.
        var tables = ModelIntrospection.Tables(ModelIntrospection.DestinationModel());

        foreach (var table in tables)
            Assert.DoesNotContain(table.Columns, c => c.Name == "xmin");
    }

    [Fact]
    public void Identity_columns_are_written_so_identifiers_survive()
    {
        // The opposite of the rule above, and the reason it cannot just be "skip generated
        // columns". Identity columns are GENERATED BY DEFAULT, which permits an explicit value,
        // and preserving the identifiers a row already had is the entire point of a migration —
        // audit rows reference them.
        var tables = ModelIntrospection.Tables(ModelIntrospection.AuditModel());
        var auditLogs = Assert.Single(tables, t => t.Name == "AuditLogs");

        Assert.Contains(auditLogs.Columns, c => c.Name == "Id");
    }

    [Fact]
    public void Every_table_has_columns_to_copy()
    {
        var tables = ModelIntrospection.Tables(ModelIntrospection.DestinationModel());

        Assert.NotEmpty(tables);
        foreach (var table in tables)
            Assert.True(table.Columns.Count > 0, $"{table.Name} has no writable columns");
    }

    [Fact]
    public void Case_insensitive_columns_resolve_to_real_table_and_column_names()
    {
        // The preflight sweep builds MariaDB queries out of these names, so a stale entity name
        // would produce a query against a table that does not exist rather than a missed check.
        var model = ModelIntrospection.DestinationModel();
        var tableNames = ModelIntrospection.Tables(model).Select(t => t.Name).ToHashSet(StringComparer.Ordinal);
        var columns = ModelIntrospection.CaseInsensitiveColumns(model).ToList();

        Assert.NotEmpty(columns);
        foreach (var (table, column) in columns)
        {
            Assert.Contains(table, tableNames);
            Assert.False(string.IsNullOrWhiteSpace(column));
        }
    }

    // ── Type conversions ──────────────────────────────────────────────────────

    [Fact]
    public void A_timestamp_is_stamped_as_utc_rather_than_converted()
    {
        // The quiet one. MySQL's datetime(6) carries no zone, so MySqlConnector hands back
        // DateTimeKind.Unspecified, and Npgsql refuses anything but Utc for timestamptz. Every
        // stored value was already UTC, so the wall clock must survive untouched — converting
        // would shift every timestamp in the database by the offset of whichever machine happened
        // to run the migration.
        var asStored = new DateTime(2026, 9, 18, 14, 30, 0, DateTimeKind.Unspecified);

        var coerced = Assert.IsType<DateTime>(ValueCoercion.Coerce(asStored, typeof(DateTime)));

        Assert.Equal(DateTimeKind.Utc, coerced.Kind);
        Assert.Equal(asStored.TimeOfDay, coerced.TimeOfDay);
        Assert.Equal(asStored.Date, coerced.Date);
    }

    [Theory]
    [InlineData((sbyte)1, true)]
    [InlineData((sbyte)0, false)]
    [InlineData(1, true)]
    [InlineData(0, false)]
    public void A_tinyint_becomes_a_boolean(object stored, bool expected)
    {
        Assert.Equal(expected, ValueCoercion.Coerce(stored, typeof(bool)));
    }

    [Fact]
    public void A_char36_identifier_becomes_a_native_uuid()
    {
        var id = Guid.NewGuid();

        Assert.Equal(id, ValueCoercion.Coerce(id.ToString(), typeof(Guid)));
    }

    [Fact]
    public void Binary_columns_cross_byte_for_byte()
    {
        // These carry protected key material, raw certificates and wrapped secrets. Anything
        // other than the same bytes is a silently broken CA.
        var bytes = RandomNumberGenerator.GetBytes(64);

        Assert.Same(bytes, ValueCoercion.Coerce(bytes, typeof(byte[])));
    }

    [Fact]
    public void A_null_stays_null_whatever_the_target()
    {
        Assert.Null(ValueCoercion.Coerce(null, typeof(Guid)));
        Assert.Null(ValueCoercion.Coerce(DBNull.Value, typeof(string)));
    }

    [Fact]
    public void A_value_that_cannot_be_represented_names_itself()
    {
        // A conversion failure mid-copy has to say which column and which value, because the
        // alternative is an operator staring at a cast exception from a table of sixty-nine.
        var ex = Assert.Throws<InvalidOperationException>(
            () => ValueCoercion.Coerce("not-a-guid", typeof(Guid)));

        Assert.Contains("not-a-guid", ex.Message);
        Assert.Contains("Guid", ex.Message);
    }

    // ── The one table that does not copy straight ─────────────────────────────

    [Fact]
    public void An_enrollment_token_is_hashed_on_the_way_across()
    {
        // 0.3.0 stored the token itself; 0.3.1 stores a SHA-256 of it, so tokens already issued
        // keep working and stop being readable. Hashed rather than moved is the whole change.
        var transform = new EnrollmentTokenTransform();
        const string token = "ELCI2hOlNcwTH6so-tOosqUk25L9Bnwt0vWQcKrmCYA";
        var expected = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(token)));

        var produced = transform.Produce("Token", new Dictionary<string, object?> { ["Token"] = token });

        Assert.Equal(expected, produced);
        Assert.NotEqual(token, produced);
    }

    [Fact]
    public void The_cmp_secret_columns_are_left_empty()
    {
        // A CMP row's shared secret was its token value, and on 0.3.1 that secret lives wrapped
        // under a key only the signer holds. Preflight refuses while any CMP token is still live,
        // so every CMP row that reaches the copy is revoked or expired: its history is worth
        // keeping and its secret is not.
        var transform = new EnrollmentTokenTransform();
        var row = new Dictionary<string, object?> { ["Token"] = "whatever-it-was" };

        Assert.Null(transform.Produce("CmpSecretWrapped", row));
        Assert.Null(transform.Produce("CmpSecretLastFour", row));
    }

    [Fact]
    public void Only_the_enrollment_token_table_is_transformed()
    {
        Assert.NotNull(RowTransforms.For("EnrollmentTokens"));
        Assert.Null(RowTransforms.For("Certificates"));
        Assert.Null(RowTransforms.For("Users"));
    }

    [Fact]
    public void The_transform_declares_the_source_column_it_reads()
    {
        // The copier only reads columns it was asked for, so a transform that needs a source
        // column it does not write has to say so or it silently produces nulls.
        var transform = new EnrollmentTokenTransform();

        Assert.Contains("Token", transform.RequiresSourceColumns);
    }

    // ── The command line ──────────────────────────────────────────────────────

    private static string[] MinimalArgs() =>
    [
        "--source-host", "mariadb.internal", "--source-user", "root", "--source-password", "s",
        "--source-app-db", "modularca", "--source-audit-db", "modularca_audit",
        "--target-host", "pg.internal", "--target-admin-user", "postgres", "--target-admin-password", "p",
        "--target-app-db", "modularca", "--target-audit-db", "modularca_audit",
        "--target-app-role", "modularca", "--target-audit-role", "modularca_audit",
    ];

    [Fact]
    public void The_default_ports_are_the_two_engines_defaults()
    {
        var options = CommandLine.Parse(MinimalArgs());

        Assert.Equal(3306, options.SourcePort);
        Assert.Equal(5432, options.TargetPort);
    }

    [Fact]
    public void The_destination_names_are_optional_and_follow_the_source()
    {
        // These were required once, which is most of what made the first version of this command
        // twelve options long. A PostgreSQL server has no database of the source's name yet, so
        // reusing it is both safe and the name the operator already has in their head.
        var full = MinimalArgs();
        var at = Array.IndexOf(full, "--target-app-role");
        var args = full.Take(at).Concat(full.Skip(at + 2)).ToArray();   // drop the flag and its value

        var options = CommandLine.Parse(args);

        Assert.Equal(options.SourceUser, options.TargetAppRole);
    }

    [Fact]
    public void A_missing_option_that_cannot_be_defaulted_is_named()
    {
        // The source database name has nowhere to come from without a db.yaml, so it stays
        // required — and the message has to say that it would normally have been read from one,
        // otherwise an operator on a host where discovery failed has no idea why.
        var full = MinimalArgs();
        var at = Array.IndexOf(full, "--source-app-db");
        var args = full.Take(at).Concat(full.Skip(at + 2)).ToArray();

        var ex = Assert.Throws<ArgumentException>(() => CommandLine.Parse(args));

        Assert.Contains("--source-app-db", ex.Message);
        Assert.Contains("db.yaml", ex.Message);
    }

    [Fact]
    public void A_value_that_is_not_a_port_is_refused()
    {
        var args = MinimalArgs().Concat(["--target-port", "not-a-port"]).ToArray();

        var ex = Assert.Throws<ArgumentException>(() => CommandLine.Parse(args));

        Assert.Contains("--target-port", ex.Message);
    }

    [Fact]
    public void Dry_run_and_keep_on_failure_are_flags_not_values()
    {
        var options = CommandLine.Parse(MinimalArgs().Concat(["--dry-run", "--keep-on-failure"]).ToArray());

        Assert.True(options.DryRun);
        Assert.True(options.KeepOnFailure);
    }

    [Fact]
    public void Tls_is_preferred_rather_than_disabled_by_default()
    {
        // The CA connects to its database before it has issued the database a certificate, so
        // require would be a bootstrap deadlock and disable would be a choice nobody made.
        Assert.Equal("prefer", CommandLine.Parse(MinimalArgs()).TargetSslMode);
    }
}
