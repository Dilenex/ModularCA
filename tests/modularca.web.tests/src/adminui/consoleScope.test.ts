import { describe, expect, it } from 'vitest';
import { CEREMONY_UNKNOWN_HINT, INSTANCE_SCOPE, ceremonyRequiredFor, createCaButtonLabel } from '@adminui/pages/caCreation';
import { CEREMONIES_PATH, ceremonyLink, ceremonyPath } from '@adminui/pages/ceremonyLinks';
import {
    GROUP_TYPE_FILTERS, INSTANCE_GROUP_SCOPE, createGroupBody, groupKind, groupScopeName, groupTypeLabel, spaceNameMap,
} from '@adminui/pages/groupScope';
import { INSTANCE_REALMS_ANCHOR, SPACE_REALMS_ANCHOR, explainMsaeFailure, realmBindingsPath } from '@adminui/pages/msaeRefusals';
import { quorumProblem } from '@adminui/components/userQuorum';

/**
 * The Create CA panel's button: "Start … CA Ceremony" when the target scope requires a ceremony,
 * the instance included, and a plain create label with a hint when the console cannot tell.
 */
describe('the Create CA button', () => {
    const source = { instance: true, spaces: [{ id: 's1', requireKeyCeremony: false }, { id: 's2', requireKeyCeremony: true }] };

    it('reads the instance policy for "Instance (no space)" and the space policy otherwise', () => {
        expect(ceremonyRequiredFor(INSTANCE_SCOPE, source)).toBe(true);
        expect(ceremonyRequiredFor(INSTANCE_SCOPE, { ...source, instance: false })).toBe(false);
        expect(ceremonyRequiredFor('s1', source)).toBe(false);
        expect(ceremonyRequiredFor('s2', source)).toBe(true);
    });

    it('is unknown with no target, an unread instance policy, or a space the list does not carry', () => {
        expect(ceremonyRequiredFor('', source)).toBeNull();
        expect(ceremonyRequiredFor(INSTANCE_SCOPE, { spaces: [] })).toBeNull();
        expect(ceremonyRequiredFor(INSTANCE_SCOPE, { instance: null, spaces: [] })).toBeNull();
        expect(ceremonyRequiredFor('s9', source)).toBeNull();
        expect(ceremonyRequiredFor('s1', { spaces: [{ id: 's1' }] })).toBeNull();
    });

    it('labels a ceremony as a ceremony and falls back to a plain create', () => {
        expect(createCaButtonLabel('root', true, false)).toBe('Start Root CA Ceremony');
        expect(createCaButtonLabel('intermediate', true, false)).toBe('Start Intermediate CA Ceremony');
        expect(createCaButtonLabel('intermediate', false, false)).toBe('Create Intermediate CA');
        expect(createCaButtonLabel('intermediate', null, false)).toBe('Create Intermediate CA');
        expect(createCaButtonLabel('root', true, true)).toBe('Starting Ceremony...');
        expect(createCaButtonLabel('root', false, true)).toBe('Creating...');
        expect(createCaButtonLabel('root', null, true)).toBe('Submitting...');
        expect(CEREMONY_UNKNOWN_HINT).toMatch(/ceremony/);
    });
});

/** A toast quotes the same path the router opens the ceremony's drawer at. */
describe('ceremony links', () => {
    it('route /ceremonies/:id and quote it under /admin', () => {
        expect(CEREMONIES_PATH).toBe('/ceremonies');
        expect(ceremonyPath('6d1f3c2a-4b5e-4f60-8a71-0b2c3d4e5f60')).toBe('/ceremonies/6d1f3c2a-4b5e-4f60-8a71-0b2c3d4e5f60');
        expect(ceremonyLink('abc')).toBe('/admin/ceremonies/abc');
        expect(ceremonyPath('a/b')).toBe('/ceremonies/a%2Fb');
    });
});

/** The Groups page: kinds, scope names (never ids) and the create body. */
describe('the Groups page', () => {
    it('tells a space-wide auto group from a CA one', () => {
        expect(groupKind({ isSystemGroup: true, isAutoGenerated: true })).toBe('system');
        expect(groupKind({ isAutoGenerated: true, spaceId: 's1', certificateAuthorityId: null })).toBe('space');
        expect(groupKind({ isAutoGenerated: true, spaceId: 's1', certificateAuthorityId: 'ca1' })).toBe('ca');
        // An instance CA's auto groups have no space.
        expect(groupKind({ isAutoGenerated: true, spaceId: null, certificateAuthorityId: 'ca1' })).toBe('ca');
        expect(groupKind({ isAutoGenerated: false, spaceId: 's1' })).toBe('custom');
        expect(groupTypeLabel({ isAutoGenerated: true, spaceId: 's1' })).toBe('Space (Auto)');
        expect(groupTypeLabel({ isAutoGenerated: true, spaceId: 's1', certificateAuthorityId: 'ca1' })).toBe('CA (Auto)');
        expect(GROUP_TYPE_FILTERS.map((o) => o.value)).toEqual(['system', 'space', 'ca', 'custom']);
    });

    it('names a group\'s scope from the first source that knows the space, and never shows its id', () => {
        const names = spaceNameMap(
            [{ id: 's1', name: 'From admin list' }],
            [{ id: 's1', name: 'From /me' }, { id: 's2', name: 'Two' }],
            [{ id: 's3', name: 'From CA list' }, { id: null, name: 'ignored' }, { id: 's4', name: '' }],
        );
        expect(groupScopeName({ spaceId: null }, names)).toBe('Instance');
        expect(groupScopeName({ spaceId: 's1' }, names)).toBe('From admin list');
        expect(groupScopeName({ spaceId: 's2' }, names)).toBe('Two');
        expect(groupScopeName({ spaceId: 's3' }, names)).toBe('From CA list');
        expect(groupScopeName({ spaceId: 's4' }, names)).toBe('Unknown space');
        expect(groupScopeName({ spaceId: '6d1f3c2a-4b5e-4f60-8a71-0b2c3d4e5f60' }, names)).toBe('Unknown space');
    });

    it('sends scope "instance" for an instance group, and a space or CA otherwise', () => {
        const form = { name: 'g', displayName: 'G', templateName: 'Requester', certificateAuthorityId: '', spaceId: '' };
        expect(createGroupBody({ ...form, spaceId: INSTANCE_GROUP_SCOPE })).toEqual({
            name: 'g', displayName: 'G', templateName: 'Requester', certificateAuthorityId: null, spaceId: null, scope: 'instance',
        });
        expect(createGroupBody({ ...form, spaceId: 's1' })).toEqual({
            name: 'g', displayName: 'G', templateName: 'Requester', certificateAuthorityId: null, spaceId: 's1',
        });
        expect(createGroupBody({ ...form, certificateAuthorityId: 'ca1', spaceId: INSTANCE_GROUP_SCOPE })).toEqual({
            name: 'g', displayName: 'G', templateName: 'Requester', certificateAuthorityId: 'ca1', spaceId: null,
        });
    });
});

/** An MSAE refusal links to the realm bindings of the CA's scope, only for a viewer who can open them. */
describe('the MSAE realm link', () => {
    const refusal = { errorMessage: 'Kerberos token refused: UnknownRealm', realm: 'LAB.TEST', caLabel: 'lab-ca' };

    it('points at the space page\'s realm section, or the instance section for an instance CA', () => {
        expect(realmBindingsPath('s1')).toBe(`/spaces/s1#${SPACE_REALMS_ANCHOR}`);
        expect(realmBindingsPath(null)).toBe(`/spaces#${INSTANCE_REALMS_ANCHOR}`);
        expect(explainMsaeFailure({ ...refusal, spaceId: 's1' }, { canOpenRealms: true })?.link?.path).toBe(`/spaces/s1#${SPACE_REALMS_ANCHOR}`);
        expect(explainMsaeFailure({ ...refusal, spaceId: null }, { canOpenRealms: true })?.link?.path).toBe(`/spaces#${INSTANCE_REALMS_ANCHOR}`);
    });

    it('is hidden from a viewer who cannot open the realm pages', () => {
        const why = explainMsaeFailure({ ...refusal, spaceId: 's1' }, { canOpenRealms: false });
        expect(why?.title).toBe('Realm not bound');
        expect(why?.link).toBeUndefined();
        expect(explainMsaeFailure({ ...refusal, spaceId: 's1' })?.link).toBeUndefined();
    });

    it('leaves the links that are not realm links alone', () => {
        const why = explainMsaeFailure({ errorMessage: 'No credential presented', caLabel: 'lab-ca' }, { canOpenRealms: false });
        expect(why?.link?.path).toBe('/authorities/protocols?ca=lab-ca');
    });
});

/** The user-quorum Save is disabled, with a reason, for a value the server would refuse. */
describe('quorumProblem', () => {
    it('allows blank only where inheriting is', () => {
        expect(quorumProblem('', { allowInherit: true })).toBeNull();
        expect(quorumProblem('  ', { allowInherit: false })).toBe('Enter a quorum.');
    });

    it('refuses zero and anything that is not a whole number', () => {
        expect(quorumProblem('0', { allowInherit: true })).toMatch(/at least 1/);
        expect(quorumProblem('1.5', { allowInherit: true })).toBe('Enter a whole number.');
        expect(quorumProblem('-2', { allowInherit: true })).toBe('Enter a whole number.');
    });

    it('refuses a CA quorum above its ceiling and names the ceiling', () => {
        expect(quorumProblem('3', { allowInherit: true, max: 2, maxLabel: "the instance's quorum" })).toBe("Can't exceed the instance's quorum (2).");
        expect(quorumProblem('2', { allowInherit: true, max: 2 })).toBeNull();
        expect(quorumProblem('5', { allowInherit: true, max: null })).toBeNull();
    });
});
